// Convert the pinned CC0 DiceBear definition into editable numeric pixel parts.
// Run from the repository root: node scripts/import-dicebear-avatar.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = JSON.parse(readFileSync(new URL('scripts/sources/dicebear-pixel-art.json', root), 'utf8'));
const directory = new URL('src/renderer/parts/avatar/', root);
mkdirSync(directory, { recursive: true });

// Pixel Art uses only orthogonal SVG paths. Keep unsupported commands fatal.
function polygons(path) {
  const tokens = path.match(/[a-zA-Z]|-?(?:\d*\.\d+|\d+)/g);
  const result = [];
  let x = 0, y = 0, startX = 0, startY = 0, polygon;
  for (let i = 0; i < tokens.length;) {
    const command = tokens[i++];
    const relative = command === command.toLowerCase();
    switch (command.toLowerCase()) {
      case 'm': {
        x = Number(tokens[i++]) + (relative ? x : 0);
        y = Number(tokens[i++]) + (relative ? y : 0);
        startX = x; startY = y;
        polygon = [[x, y]];
        result.push(polygon);
        break;
      }
      case 'h': x = Number(tokens[i++]) + (relative ? x : 0); polygon.push([x, y]); break;
      case 'v': y = Number(tokens[i++]) + (relative ? y : 0); polygon.push([x, y]); break;
      case 'z': x = startX; y = startY; break;
      default: throw new Error(`Unsupported path command ${command}`);
    }
  }
  return result;
}

function contains(contours, px, py, evenOdd) {
  let winding = 0;
  for (const contour of contours) {
    for (let i = 0; i < contour.length; i++) {
      const [x1, y1] = contour[i];
      const [x2, y2] = contour[(i + 1) % contour.length];
      const intersection = x1 + (py - y1) * (x2 - x1) / (y2 - y1);
      if (y1 <= py && y2 > py && intersection > px) winding++;
      if (y2 <= py && y1 > py && intersection > px) winding--;
    }
  }
  return evenOdd ? Math.abs(winding) % 2 === 1 : winding !== 0;
}

function coverage(element, offset) {
  // SVG crispEdges snaps edges to device pixels, including half-pixel ties.
  const contours = polygons(element.attributes.d).map(contour =>
    contour.map(([x, y]) => [Math.round(x + offset[0]), Math.round(y + offset[1])])
  );
  return Array.from({ length: 16 }, (_, y) => Array.from({ length: 16 }, (_, x) =>
    contains(contours, x + 0.5, y + 0.5, element.attributes['fill-rule'] === 'evenodd')
  ));
}

function compile(elements, offset, tags) {
  const masks = new Map();
  function findMasks(nodes) {
    for (const node of nodes) {
      if (node.name === 'mask') masks.set(node.attributes.id, node);
      if (node.children) findMasks(node.children);
    }
  }
  findMasks(elements);
  const part = { layers: [] };
  if (tags) part.tags = tags;
  function visit(nodes, mask) {
    for (const node of nodes) {
      if (node.name === 'defs') continue;
      if (node.name === 'g') {
        const id = node.attributes.mask.match(/^url\(#(.+)\)$/)?.[1];
        const paths = masks.get(id)?.children;
        if (mask || paths?.length !== 1) throw new Error('Unsupported mask');
        part.opacity = Number(paths[0].attributes.opacity ?? 1);
        visit(node.children, coverage(paths[0], offset));
        continue;
      }
      if (node.name !== 'path') throw new Error(`Unsupported element ${node.name}`);
      const pixels = coverage(node, offset).map((row, y) => row.map((filled, x) => filled && (!mask || mask[y][x]) ? 1 : 0));
      const points = pixels.flatMap((row, y) => row.flatMap((v, x) => v ? [[x, y]] : []));
      if (!points.length) continue;
      const minX = Math.min(...points.map(p => p[0])), maxX = Math.max(...points.map(p => p[0]));
      const minY = Math.min(...points.map(p => p[1])), maxY = Math.max(...points.map(p => p[1]));
      const fill = node.attributes.fill;
      const role = typeof fill === 'string' ? fill.toLowerCase() : fill.name;
      const layer = {
        pixels: pixels.slice(minY, maxY + 1).map(row => row.slice(minX, maxX + 1)),
        slotMap: { 1: role }, offsetX: minX, offsetY: minY,
      };
      const opacity = Number(node.attributes['fill-opacity'] ?? 1) * Number(node.attributes.opacity ?? 1);
      if (opacity !== 1) layer.opacity = opacity;
      part.layers.push(layer);
    }
  }
  visit(elements);
  return part;
}

function emit(name, value) {
  const type = name === 'body' ? 'AvatarPart' : 'Record<string, AvatarPart>';
  // Keep each numeric pixel row on one line for editing.
  const data = JSON.stringify(value, null, 2).replace(/\[\s+([01](?:,\s+[01])*)\s+\]/g, (_, row) => `[${row.replace(/\s+/g, '')}]`);
  const output = `// DiceBear Pixel Art (CC0 1.0). Generated by scripts/import-dicebear-avatar.mjs.\nimport type { AvatarPart } from './types.ts';\n\nconst ${name} = ${data} satisfies ${type};\n\nexport default ${name};\n`;
  writeFileSync(new URL(`${name}.ts`, directory), output);
}

emit('body', compile(source.canvas.elements.filter(e => e.type === 'element'), [0, 0]));
for (const [name, component] of Object.entries(source.components)) {
  const canvasElement = source.canvas.elements.find(e => e.type === 'component' && e.name === name);
  const numbers = canvasElement.attributes?.transform?.match(/-?\d+(?:\.\d+)?/g)?.map(Number) ?? [0, 0];
  const offset = [numbers[0], numbers[1] ?? 0];
  emit(name, Object.fromEntries(Object.entries(component.variants).map(([variant, definition]) =>
    [variant, compile(definition.elements, offset, definition.tags)]
  )));
}

const palettes = Object.fromEntries(Object.entries(source.colors).map(([name, color]) => [`${name}Color`, color.values]));
writeFileSync(new URL('palette.ts', directory), `// DiceBear Pixel Art (CC0 1.0). Generated by scripts/import-dicebear-avatar.mjs.\nexport const AVATAR_COLOR_PRESETS = ${JSON.stringify(palettes, null, 2)} as const;\n`);
const colorNames = JSON.parse(readFileSync(new URL('scripts/sources/avatar-color-names.json', root), 'utf8'));
writeFileSync(new URL('color-names.ts', directory), `// Generic display labels from scripts/sources/avatar-color-names.json.\n// Generated by scripts/import-dicebear-avatar.mjs. Existing hex values are preserved.\nexport const AVATAR_COLOR_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(colorNames.colors, null, 2)};\n`);
console.log(`Imported ${Object.keys(source.components).length} features into ${fileURLToPath(directory)}`);
